# tests.unit 子包标记文件
# ---------------------------------------------------------------------------
#
# 作用：把 tests/unit/ 标记成 tests 包下的一个子包。
#
# 这里为什么要单独一个 __init__.py，而不是直接在 tests/ 下铺一堆 test_*.py？
#   我们把测试按"层级"分目录放：
#     tests/unit/          —— 单元测试（不依赖文件系统之外的任何东西）
#     tests/integration/   —— 预留：以后要跑真 CLI、真网络的集成测试
#     tests/gateway/       —— 预留：Node gateway 相关的 Python 侧辅助测试
#   目录分层之后，每一层都要有自己的 __init__.py，理由见 tests/__init__.py。
#
# 设计约定：
#   - unit 层的测试里，允许起真 subprocess（因为 executor 本来就是跑
#     subprocess），但不允许访问网络、不允许依赖"项目之外"的文件。
#   - 跨进程的持久状态（比如 session 目录）必须通过 conftest.py 的
#     sandbox_session fixture 走 tmp_path 隔离，不要写真实的
#     /tmp/mini-agent-sandbox。
# ---------------------------------------------------------------------------
